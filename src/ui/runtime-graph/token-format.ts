import type { TaskTokensUsage } from "../../runtime-graph/types.ts";

/**
 * Formats token count compactly for task row display (e.g. "450 tok", "1.4k tok", "12k tok").
 */
export function formatTokens(tokens?: number): string | null {
	if (tokens === undefined || tokens === null || tokens <= 0 || !Number.isFinite(tokens)) {
		return null;
	}
	if (tokens < 1000) {
		return `${Math.round(tokens)} tok`;
	}
	if (tokens < 10_000) {
		return `${(tokens / 1000).toFixed(1)}k tok`;
	}
	if (tokens < 1_000_000) {
		return `${Math.round(tokens / 1000)}k tok`;
	}
	return `${(tokens / 1_000_000).toFixed(1)}M tok`;
}

/**
 * Formats a detailed token usage breakdown for the inspector (details panel).
 */
export function formatDetailedTokens(tokens?: TaskTokensUsage): string | null {
	if (!tokens) return null;
	const total = tokens.total ?? ((tokens.input ?? 0) + (tokens.output ?? 0));
	if (total <= 0) return null;

	const parts: string[] = [];
	if (tokens.input !== undefined && tokens.input > 0) {
		parts.push(`${tokens.input.toLocaleString()} in`);
	}
	if (tokens.output !== undefined && tokens.output > 0) {
		parts.push(`${tokens.output.toLocaleString()} out`);
	}
	if (tokens.reasoning !== undefined && tokens.reasoning > 0) {
		parts.push(`${tokens.reasoning.toLocaleString()} reasoning`);
	}
	if (tokens.cacheRead !== undefined && tokens.cacheRead > 0) {
		parts.push(`${tokens.cacheRead.toLocaleString()} cache`);
	}

	const totalStr = `${total.toLocaleString()} total`;
	return parts.length > 0 ? `${totalStr} (${parts.join(" · ")})` : totalStr;
}

/**
 * Calculates the active (uncached) tokens consumed and generated by a step:
 * (input ?? 0) + (output ?? 0) + (reasoning ?? 0).
 * If no breakdown is available, falls back to uncached delta (total - cacheRead) or total.
 */
export function calculateStepTokens(usage?: TaskTokensUsage): number | undefined {
	if (!usage) return undefined;
	const input = usage.input ?? 0;
	const output = usage.output ?? 0;
	const reasoning = usage.reasoning ?? 0;
	const active = input + output + reasoning;
	if (active > 0) return active;
	if (typeof usage.total === "number" && usage.total > 0 && typeof usage.cacheRead === "number") {
		const uncached = usage.total - usage.cacheRead;
		if (uncached > 0) return uncached;
	}
	if (typeof usage.total === "number" && usage.total > 0) return usage.total;
	return undefined;
}

/**
 * Formats step token count cleanly without unit suffixes or plus signs (e.g. "320", "1.4k", "12k", "1.2M").
 */
export function formatStepTokens(tokens?: number): string | null {
	if (tokens === undefined || tokens === null || tokens <= 0 || !Number.isFinite(tokens)) {
		return null;
	}
	if (tokens < 1000) {
		return `${Math.round(tokens)}`;
	}
	if (tokens < 10_000) {
		const str = (tokens / 1000).toFixed(1);
		return str.endsWith(".0") ? `${str.slice(0, -2)}k` : `${str}k`;
	}
	if (tokens < 1_000_000) {
		return `${Math.round(tokens / 1000)}k`;
	}
	const str = (tokens / 1_000_000).toFixed(1);
	return str.endsWith(".0") ? `${str.slice(0, -2)}M` : `${str}M`;
}

/**
 * Formats a token delta compactly for row display (e.g. "+1.4k", "+450", "+0", "-15k").
 */
export function formatTokenDelta(delta?: number): string | null {
	if (delta === undefined || delta === null || !Number.isFinite(delta)) {
		return null;
	}
	const sign = delta >= 0 ? "+" : "-";
	const abs = Math.abs(delta);
	if (abs < 1000) {
		return `${sign}${Math.round(abs)}`;
	}
	if (abs < 10_000) {
		return `${sign}${(abs / 1000).toFixed(1)}k`;
	}
	if (abs < 1_000_000) {
		return `${sign}${Math.round(abs / 1000)}k`;
	}
	return `${sign}${(abs / 1_000_000).toFixed(1)}M`;
}

